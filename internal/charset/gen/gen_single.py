#!/usr/bin/env python3
"""Generate singlebyte.go: the single-byte encodings of the WHATWG
Encoding Standard that tables.go does not have, from the standard's index
files (https://encoding.spec.whatwg.org/index-NAME.txt), with their
labels (encodings.json).

    python3 gen_single.py INDEXDIR > ../singlebyte.go

INDEXDIR holds index-NAME.txt for each NAME below, and encodings.json.
The tables are the standard's, which is what HTML is decoded by; where
Python's codec of the same name maps a byte otherwise, the difference is
printed to standard error, for the record.
"""
import codecs, json, os, sys

# Go name, WHATWG index, Python codec (or None)
SETS = [
    ("ibm866", "ibm866", "cp866"),
    ("iso8859_2", "iso-8859-2", "iso8859_2"), ("iso8859_3", "iso-8859-3", "iso8859_3"),
    ("iso8859_4", "iso-8859-4", "iso8859_4"), ("iso8859_5", "iso-8859-5", "iso8859_5"),
    ("iso8859_6", "iso-8859-6", "iso8859_6"), ("iso8859_7", "iso-8859-7", "iso8859_7"),
    ("iso8859_8", "iso-8859-8", "iso8859_8"), ("iso8859_10", "iso-8859-10", "iso8859_10"),
    ("iso8859_13", "iso-8859-13", "iso8859_13"), ("iso8859_14", "iso-8859-14", "iso8859_14"),
    ("iso8859_15", "iso-8859-15", "iso8859_15"), ("iso8859_16", "iso-8859-16", "iso8859_16"),
    ("koi8r", "koi8-r", "koi8_r"), ("koi8u", "koi8-u", "koi8_u"), ("macCyrillic", "x-mac-cyrillic", "mac_cyrillic"),
]
d = sys.argv[1]
labels = {}
for g in json.load(open(os.path.join(d, "encodings.json"))):
    for e in g["encodings"]:
        labels[e["name"].lower()] = e["labels"]

print("// Code generated by gen/gen_single.py from the WHATWG Encoding Standard's")
print("// index files; DO NOT EDIT.")
print()
print("package charset")
print()
print("// The upper halves (bytes 0x80 to 0xFF) of the single-byte encodings of")
print("// the Encoding Standard that tables.go does not have, as its index files")
print("// give them. A zero is a byte the index leaves undefined (U+FFFD).")
for go, name, py in SETS:
    t = [0] * 128
    for line in open(os.path.join(d, f"index-{name}.txt")):
        line = line.split("#")[0].strip()
        if not line:
            continue
        p, cp = line.split()[:2]
        t[int(p)] = int(cp, 16)
    if py:
        diff = []
        for i in range(128):
            try:
                c = ord(bytes([0x80 + i]).decode(py))
            except UnicodeDecodeError:
                c = 0
            if c != t[i]:
                diff.append(f"0x{0x80 + i:02X}: WHATWG {t[i]:04X}, Python {c:04X}")
        if diff:
            print(f"{name} differs from Python's {py} at {len(diff)} bytes: " + "; ".join(diff[:6]), file=sys.stderr)
    print()
    print(f"var {go} = [128]uint16{{")
    for r in range(0, 128, 16):
        print("\t" + ", ".join(f"0x{c:04X}" if c else "0" for c in t[r:r + 16]) + ",")
    print("}")
print()
print("// singleLabels maps the Encoding Standard's labels of these encodings to")
print("// them; iso-8859-8-i is iso-8859-8 here (the two differ only in how")
print("// text direction is meant).")
print("var singleLabels = map[string]Encoding{")
enc = {"ibm866": "IBM866", "iso-8859-2": "ISO8859_2", "iso-8859-3": "ISO8859_3", "iso-8859-4": "ISO8859_4",
       "iso-8859-5": "ISO8859_5", "iso-8859-6": "ISO8859_6", "iso-8859-7": "ISO8859_7", "iso-8859-8": "ISO8859_8",
       "iso-8859-8-i": "ISO8859_8", "iso-8859-10": "ISO8859_10", "iso-8859-13": "ISO8859_13", "iso-8859-14": "ISO8859_14",
       "iso-8859-15": "ISO8859_15", "iso-8859-16": "ISO8859_16", "koi8-r": "KOI8R", "koi8-u": "KOI8U",
       "x-mac-cyrillic": "MacCyrillic", "euc-jp": "EUCJP", "gb18030": "GB18030"}
for name, go in enc.items():
    print("\t" + " ".join(f'"{l}": {go},' for l in labels[name]))
print("}")
