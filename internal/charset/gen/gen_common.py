#!/usr/bin/env python3
"""Generate common.go: the most frequent Chinese characters, in their
Simplified and Traditional forms, as a bitmap over U+4E00 to U+9FFF, for
the encoding detector (detect.go).

Input: the Unicode Consortium's Unihan database (Unihan.zip of the UCD),
unpacked. Frequency is kHanyuPinlu (counts from the Xiandai Hanyu Pinlu
Cidian, summed over a character's readings; it lists some Traditional
forms as well); to the 1,000 most frequent is added each one's
kTraditionalVariant.

    python3 gen_common.py UNIHAN_DIR > ../common.go
"""
import re, sys

N = 1000
LO, HI = 0x4E00, 0xA000
d = sys.argv[1]
counts = {}
for line in open(f"{d}/Unihan_Readings.txt", encoding="utf-8"):
    if "\tkHanyuPinlu\t" not in line:
        continue
    cp, _, val = line.rstrip("\n").split("\t")
    counts[int(cp[2:], 16)] = sum(int(n) for n in re.findall(r"\((\d+)\)", val))
trad = {}
for line in open(f"{d}/Unihan_Variants.txt", encoding="utf-8"):
    if "\tkTraditionalVariant\t" not in line:
        continue
    cp, _, val = line.rstrip("\n").split("\t")
    trad[int(cp[2:], 16)] = [int(v[2:], 16) for v in val.split()]
top = [c for c, _ in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])) if LO <= c < HI][:N]
common = set(top)
for c in top:
    common.update(v for v in trad.get(c, []) if LO <= v < HI)

def bitmap(name, chars, doc):
    words = [0] * ((HI - LO) // 32)
    for c in chars:
        words[(c - LO) // 32] |= 1 << ((c - LO) % 32)
    out = [f"// {doc} ({len(chars)} characters).", f"var {name} = [{len(words)}]uint32{{"]
    for i in range(0, len(words), 8):
        out.append("\t" + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
    out.append("}")
    return "\n".join(out)

print("// Code generated by gen/gen_common.py from the Unicode Consortium's")
print("// Unihan database; DO NOT EDIT.")
print()
print("package charset")
print()
print(bitmap("commonHan", common, f"commonHan holds the {N} most frequent Chinese characters and their Traditional forms (Unihan kHanyuPinlu, kTraditionalVariant)"))
