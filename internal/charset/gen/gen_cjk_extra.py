#!/usr/bin/env python3
"""Generate the tables for GB18030, EUC-JP and ISO-2022-JP.

Usage: python3 internal/charset/gen/gen_cjk_extra.py internal/charset/tables

The tables come from Python's own codecs (the Python version is written
into each file's header).
Every line after the header is "KEY VALUE", both hexadecimal.

gb18030-2.txt     two-byte GB18030: lead byte and trail byte as four hex
                  digits, then the code point. From Python's gb18030 codec.
gb18030-4.txt     the four-byte ranges of the BMP, as the WHATWG Encoding
                  Standard's index-gb18030-ranges: a pointer, then the code
                  point of the run that starts there. A pointer is
                  (b1-0x81)*12600 + (b2-0x30)*1260 + (b3-0x81)*10 + (b4-0x30).
                  Within a run, pointer and code point rise together.
                  Code points U+10000 and above are pointer 189000 +
                  (cp - 0x10000), worked out in code, not listed.
jis0208.txt       JIS X 0208 as EUC-JP bytes (row+0xA0, cell+0xA0), rows
                  1 to 94, then the code point. Derived from Python's cp932
                  codec through the Shift_JIS to JIS conversion, so it
                  agrees with the WHATWG index (for example 0xA1C1 is
                  U+FF5E, as Windows has it, not U+301C).
jis0212.txt       JIS X 0212 as the two bytes after 0x8F in EUC-JP, then
                  the code point. From Python's euc_jp codec.
"""
import sys
import os

out = sys.argv[1]
ver = "Python %d.%d.%d" % sys.version_info[:3]


def write(name, what, rows):
    with open(os.path.join(out, name), "w", encoding="ascii") as f:
        f.write("# %s: generated by gen/gen_cjk_extra.py from %s's %s\n" % (name, ver, what))
        for k, v in rows:
            f.write("%s %X\n" % (k, v))


trails = list(range(0x40, 0x7F)) + list(range(0x80, 0xFF))

# Two-byte GB18030.
rows = []
for lead in range(0x81, 0xFF):
    for trail in trails:
        try:
            s = bytes([lead, trail]).decode("gb18030")
        except UnicodeDecodeError:
            continue
        if len(s) == 1:
            rows.append(("%02X%02X" % (lead, trail), ord(s)))
write("gb18030-2.txt", "gb18030 codec (two-byte sequences)", rows)

# Four-byte GB18030 ranges in the BMP.
pairs = []
for cp in range(0x80, 0x10000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    try:
        b = chr(cp).encode("gb18030")
    except UnicodeEncodeError:
        continue
    if len(b) != 4:
        continue
    ptr = (b[0] - 0x81) * 12600 + (b[1] - 0x30) * 1260 + (b[2] - 0x81) * 10 + (b[3] - 0x30)
    pairs.append((ptr, cp))
pairs.sort()
ranges = []
for i, (p, c) in enumerate(pairs):
    if i == 0 or p != pairs[i - 1][0] + 1 or c != pairs[i - 1][1] + 1:
        ranges.append(("%X" % p, c))
write("gb18030-4.txt", "gb18030 codec (four-byte ranges of the BMP)", ranges)

# JIS X 0208 from cp932 through Shift_JIS -> JIS.
jis = {}
for s1 in list(range(0x81, 0xA0)) + list(range(0xE0, 0xF0)):
    for s2 in trails:
        if s2 > 0xFC:
            continue
        try:
            s = bytes([s1, s2]).decode("cp932")
        except UnicodeDecodeError:
            continue
        if len(s) != 1:
            continue
        row = (s1 - 0x81) * 2 + 1 if s1 <= 0x9F else (s1 - 0xC1) * 2 + 1
        if s2 >= 0x9F:
            row += 1
            cell = s2 - 0x9E
        else:
            cell = s2 - 0x40 + 1 - (1 if s2 > 0x7F else 0)
        if 1 <= row <= 94 and 1 <= cell <= 94:
            jis.setdefault((row, cell), ord(s))
write("jis0208.txt", "cp932 codec (Shift_JIS converted to JIS X 0208 rows 1-94)",
      [("%02X%02X" % (r + 0xA0, c + 0xA0), u) for (r, c), u in sorted(jis.items())])

# JIS X 0212 from euc_jp.
rows = []
for b1 in range(0xA1, 0xFF):
    for b2 in range(0xA1, 0xFF):
        try:
            s = bytes([0x8F, b1, b2]).decode("euc_jp")
        except UnicodeDecodeError:
            continue
        if len(s) == 1:
            rows.append(("%02X%02X" % (b1, b2), ord(s)))
write("jis0212.txt", "euc_jp codec (JIS X 0212, the bytes after 0x8F)", rows)
