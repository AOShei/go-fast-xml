#!/usr/bin/env python3
# Copied from go-fast-rtf internal/codepage/gen/gen_dbcs.py at commit b756076.
"""Writes the double-byte code page tables for go-fast-rtf.

Source: Python's codecs cp932, cp936, cp949 and cp950, which implement
Microsoft's Windows code pages (the Unicode Consortium's
MAPPINGS/VENDORS/MICSFT/WINDOWS/CP932.TXT, CP936.TXT, CP949.TXT, CP950.TXT).
Each output line is "<bytes in hex> <code point in hex>": two hex digits
for a single byte, four for a lead and trail byte. Bytes 0x00-0x7F are
ASCII in all four pages and are not listed. Bytes with no mapping are not
listed, nor are mappings to C1 controls (U+0080-U+009F) or the Private Use
Area (U+E000-U+F8FF), which the codecs add beyond the published files
(cp932 maps 0x80, 0xA0, 0xFD-0xFF and the user-defined area there). Usage: python3 gen_dbcs.py OUTDIR
"""
import sys, os, platform

out = sys.argv[1]

def keep(c):
    return not (0x80 <= c <= 0x9F or 0xE000 <= c <= 0xF8FF)

for cp in ("cp932", "cp936", "cp949", "cp950"):
    lines = []
    for b in range(0x80, 0x100):
        try:
            s = bytes([b]).decode(cp)
            if len(s) == 1 and keep(ord(s)):
                lines.append(f"{b:02X} {ord(s):04X}")
        except UnicodeDecodeError:
            pass
    for lead in range(0x81, 0xFF):
        for trail in range(0x40, 0xFF):
            try:
                s = bytes([lead, trail]).decode(cp)
            except UnicodeDecodeError:
                continue
            if len(s) == 1 and keep(ord(s)):
                lines.append(f"{lead:02X}{trail:02X} {ord(s):04X}")
    with open(os.path.join(out, cp + ".txt"), "w") as f:
        f.write(f"# {cp}: generated by gen/gen_dbcs.py from Python {platform.python_version()}'s {cp} codec\n")
        f.write("\n".join(lines) + "\n")
    print(cp, len(lines), "entries")
